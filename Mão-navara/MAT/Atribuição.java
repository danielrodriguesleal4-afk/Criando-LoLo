public class Atribuição {
    public static void main(String[] args) {
    // Variaveis.
        int n1 = 4;
        int n2 = 6;
        int n3 = 5;
        int n4 = 15;
        int n5 = 11;
    // Atribuições.
        n1 += 2; // C: n1 = n1 + 2;
        n2 -= 3; // C: n2 = n2 - 3;
        n3 *= 2; // C: n3 = n3 * 2;
        n4 /= 3; // C: n4 = n4 / 3;
        n5 %= 2; // C: n5 = n5 % 2;
    // Resultado.
        System.out.println("Valor n1: " + n1);
        System.out.println("Valor n2: " + n2);
        System.out.println("Valor n3: " + n3);
        System.out.println("Valor n4: " + n4);
        System.out.println("Valor n5: " + n5);
    }
}
