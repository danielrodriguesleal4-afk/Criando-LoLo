public class Operadores {
    public static void main(String[] args) {
        // Funções da Matematica em JAVA.
    float n1 = 5;
    float n2 = 4;
        // Adição no java "+"
    float r1 = n1 + n2;

    int n3 = 4;
    int n4 = 2;
        // Subtração no java "-"
    int r2 = n3 - n4;

    double n5 = 10;
    double n6 = 2;
        // Multiplicação no java "*"
    double r3 = n6 * n5;

    double n7 = 10;
    double n8 = 2;
        // Divisão no java "/"
    double r4 = n7 / n8;
    
    double n9 = 5;
    double n10 = 2;
        // O resto da divisão "&"
    double r5 = n9 % n10;
        // Mostrando os resultados.
    System.out.println("--- Resultados ---");
    System.out.println("Adição: " + r1);
    System.out.println("Subtração: " + r2);
    System.out.println("Multiplicação: " + r3);
    System.out.println("Divisão: " + r4);
    System.out.println("O resto da divisão: " + r5);
    }
}