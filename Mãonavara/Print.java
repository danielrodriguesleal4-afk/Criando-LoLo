public class Print {
    public static void main(String[] args) { 
    float nota = 8.5f;
        // Comando "print" com "f" de formatado.
    System.out.printf("A nota é %.2f \n", nota);
        /* Ó "%" representa casas decimais.
         * É os numeros após o ponto, e quantas casas deseja mostrar.
         * É por ultimo o comando "\n" e para pular uma linha.
         */
    }
}